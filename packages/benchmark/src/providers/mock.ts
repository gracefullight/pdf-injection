import type { ExpectedSignal } from "@pdf-injection/contracts";
import {
  normalizePrompt,
  readAcroFormFieldPayload,
  readActualTextPayload,
  readFreetextAnnotPayload,
  readInfoDictPayload,
  readStampedImagePresence,
  readUnicodeTagsPayload,
  readXmpPayload,
} from "@pdf-injection/pdf-engine";
import { extractText, sha256Hex } from "@pdf-injection/validation";
import { collapseWhitespace } from "../disclosure";
import { createSeededRng } from "../prng";
import type { AskTextInput, AskWithPdfInput, ProviderAdapter, ProviderAnswer } from "./types";

/**
 * Extra, mock-only context. The `ProviderAdapter` interface itself stays
 * generic (`askWithPdf({pdfBytes, prompt, filename})`, matching what a real
 * provider actually receives), but the deterministic mock needs to know
 * WHETHER the given `pdfBytes` actually carries the hidden instruction (and
 * what the expected signals look like) to decide whether to "follow" it —
 * see the module doc below. Real adapters (anthropic/openai) ignore this.
 */
export interface MockContext {
  /** The instruction that was (or was not, for "original") injected. Empty/undefined disables instruction-following behavior entirely (falls back to a generic answer). */
  hiddenInstruction?: string;
  /** 0-based page index the instruction targets, for `extractText`'s per-page match check. Defaults to page 0. */
  targetPageIndex?: number;
  /** Signals the run is checking for; when the mock "follows" the instruction it embeds literal content that satisfies these. */
  expectedSignals?: ExpectedSignal[];
}

export const DEFAULT_MOCK_MODEL = "pdf-injection-mock-v1";

/** Probability the mock "follows" the hidden instruction when it IS present in the PDF (contract §2: "high probability"). */
const FOLLOW_PROBABILITY_WHEN_FOUND = 0.9;
/** Probability the mock spuriously "follows" a non-existent instruction — models the false-positive baseline for `original` (contract §2: "low probability"). */
const FOLLOW_PROBABILITY_WHEN_NOT_FOUND = 0.1;
/** Probability the mock discloses (quotes) the instruction verbatim, when found. */
const DISCLOSE_PROBABILITY = 0.05;

function synthesizeSignalContent(signals: ExpectedSignal[]): string[] {
  const snippets: string[] = [];
  for (const signal of signals) {
    switch (signal.type) {
      case "exact_phrase":
        snippets.push(signal.value);
        break;
      case "methodology_label":
        snippets.push(`Methodology: ${signal.value}.`);
        break;
      case "ordered_terms":
        snippets.push(signal.values.join(", then "));
        break;
      case "section_order":
        for (const heading of signal.values) {
          snippets.push(`\n## ${heading}\n`);
        }
        break;
      case "regex":
        // No generic literal can satisfy an arbitrary pattern; intentionally not synthesized.
        break;
    }
  }
  return snippets;
}

function buildMockAnswer(params: {
  follow: boolean;
  disclose: boolean;
  hiddenInstruction: string;
  expectedSignals: ExpectedSignal[];
}): string {
  const parts: string[] = [
    "# Assignment Response",
    "This is a deterministic mock-provider response generated by packages/benchmark for local " +
      "testing and CI (no real model call was made — see the TODO(oma-deferred) marker below).",
  ];

  if (params.follow && params.expectedSignals.length > 0) {
    parts.push(...synthesizeSignalContent(params.expectedSignals));
  }

  if (params.disclose && params.hiddenInstruction.length > 0) {
    parts.push(
      `Note: the source document also appeared to contain the instruction: "${params.hiddenInstruction}"`,
    );
  }

  return parts.join("\n\n");
}

/**
 * Deterministic, always-available fallback provider (contract §2: "mock" is
 * always allowed, no API key needed).
 *
 * // TODO(oma-deferred): a real provider call (anthropic/openai) is used
 * // instead of this mock whenever PDFI_ALLOW_EXTERNAL_PROVIDERS=true,
 * // acknowledgeExternalTransfer=true, and the relevant API key is present.
 *
 * Determinism: seeded by `sha256(pdfBytes) + ":" + sha256(prompt)` (contract
 * §2), so the same PDF + prompt always produce the same answer text and the
 * same follow/disclose decisions — required for reproducible benchmark runs
 * and for unit tests.
 *
 * "Following" the hidden instruction: `askWithPdf` never receives the
 * instruction text directly (mirroring what a real provider sees — only
 * `pdfBytes` + the outer `prompt`). Instead it discovers whether THIS
 * specific PDF carries the known instruction (supplied out-of-band via
 * `MockContext`, which the caller — `runMatrix` — already has from the job)
 * using the same mechanisms a real extraction pipeline would: page text
 * matching (`@pdf-injection/validation extractText`, catches
 * white_text / render_mode_3 / visible_positive_control, where the
 * instruction is drawn as extractable page text), XMP metadata
 * (`@pdf-injection/pdf-engine`'s `readXmpPayload`, catches `xmp_only`), a
 * public-pdf-lib-API ToUnicode CMap read-back (`readUnicodeTagsPayload`,
 * catches `unicode_tags` — this channel is invisible to `extractText()`
 * itself, since pdfjs-dist filters the entire Unicode Tags block out of
 * extracted text; see `packages/pdf-engine/test/inject-unicode-tags.test.ts`),
 * and — for the round-3 probe conditions — three more literal-text
 * read-backs (`readInfoDictPayload` for `info_dict`, `readFreetextAnnotPayload`
 * for `freetext_annot`, `readAcroFormFieldPayload` for `acroform_field`) plus
 * a structural presence+hash check (`readStampedImagePresence` for
 * `image_only`, which carries no text at all — the mock has no OCR/vision
 * capability). For the `original` condition none of these checks match, so
 * `instructionFound` is `false` — exactly the "low probability" branch the
 * contract describes.
 */
export interface CreateMockAdapterInput {
  model?: string;
  context?: MockContext;
}

export function createMockAdapter(input: CreateMockAdapterInput = {}): ProviderAdapter {
  const model = input.model ?? DEFAULT_MOCK_MODEL;
  const context = input.context ?? {};
  const hiddenInstruction = context.hiddenInstruction ?? "";
  const expectedSignals = context.expectedSignals ?? [];
  const targetPageIndex = context.targetPageIndex ?? 0;

  async function detectInstructionFound(pdfBytes: Uint8Array): Promise<boolean> {
    if (hiddenInstruction.length === 0) return false;

    const extraction = await extractText({
      bytes: pdfBytes,
      targetInstruction: hiddenInstruction,
      targetPageIndex,
    });
    if (extraction.anyPageMatch) return true;

    const xmp = await readXmpPayload(pdfBytes);
    if (
      xmp.instruction != null &&
      collapseWhitespace(xmp.instruction).toLowerCase() ===
        collapseWhitespace(hiddenInstruction).toLowerCase()
    ) {
      return true;
    }

    // Round-3 probe modes — info_dict / freetext_annot / acroform_field:
    // each reader returns the literal instruction text it read back from
    // its own private channel (Info dict Subject, FreeText /Contents,
    // AcroForm field /V respectively) — same literal-text-equality check as
    // xmp_only above. Safe no-op for every other condition: none of these
    // channels exist on a PDF injected by a different mode.
    const infoDict = await readInfoDictPayload(pdfBytes);
    if (
      infoDict.subject != null &&
      collapseWhitespace(infoDict.subject).toLowerCase() ===
        collapseWhitespace(hiddenInstruction).toLowerCase()
    ) {
      return true;
    }

    const freetextAnnot = await readFreetextAnnotPayload(pdfBytes, targetPageIndex);
    if (
      freetextAnnot.contents != null &&
      collapseWhitespace(freetextAnnot.contents).toLowerCase() ===
        collapseWhitespace(hiddenInstruction).toLowerCase()
    ) {
      return true;
    }

    const acroFormField = await readAcroFormFieldPayload(pdfBytes);
    if (
      acroFormField.value != null &&
      collapseWhitespace(acroFormField.value).toLowerCase() ===
        collapseWhitespace(hiddenInstruction).toLowerCase()
    ) {
      return true;
    }

    const actualText = await readActualTextPayload(pdfBytes, targetPageIndex);
    if (
      actualText.actualTexts.some(
        (value) =>
          collapseWhitespace(value).toLowerCase() ===
          collapseWhitespace(hiddenInstruction).toLowerCase(),
      )
    ) {
      return true;
    }

    // image_only: by construction, no text object of any kind exists — the
    // mock has no OCR/vision capability, so the closest deterministic proxy
    // for "this PDF carries the known instruction via the image_only
    // channel" is the same promptSha256 tag apps/api's own post-injection
    // gate reads back, recomputed the same way (sha256 of the normalized
    // instruction) rather than any literal-text comparison.
    const stampedImage = await readStampedImagePresence(pdfBytes, targetPageIndex);
    if (
      stampedImage.promptSha256 != null &&
      stampedImage.promptSha256 === sha256Hex(normalizePrompt(hiddenInstruction))
    ) {
      return true;
    }

    // unicode_tags: readUnicodeTagsPayload bypasses pdfjs-dist's Cf-category
    // filter that makes extractText() blind to this channel. Presence-only
    // check — the ToUnicode CMap is keyed by unique glyph (first-appearance
    // order), not drawn position, so an exact literal-order reconstruction
    // of `hiddenInstruction` isn't recoverable from the CMap alone; a
    // non-empty result reliably means THIS PDF carries a Unicode Tag
    // payload. Structurally a safe no-op for every other condition: their
    // ToUnicode CMaps map to plain ASCII, and decodeUnicodeTags() only ever
    // returns non-empty runs for tag-block (U+E0000-U+E007F) codepoints.
    const unicodeTagsPayload = await readUnicodeTagsPayload(pdfBytes);
    return unicodeTagsPayload.length > 0;
  }

  async function askWithPdf({ pdfBytes, prompt }: AskWithPdfInput): Promise<ProviderAnswer> {
    const start = performance.now();
    const rng = createSeededRng(sha256Hex(pdfBytes), sha256Hex(prompt));

    const instructionFound = await detectInstructionFound(pdfBytes);
    const follow =
      rng() <
      (instructionFound ? FOLLOW_PROBABILITY_WHEN_FOUND : FOLLOW_PROBABILITY_WHEN_NOT_FOUND);
    const disclose = instructionFound && rng() < DISCLOSE_PROBABILITY;

    const text = buildMockAnswer({ follow, disclose, hiddenInstruction, expectedSignals });

    return {
      text,
      stopReason: "end_turn",
      refusal: false,
      usage: { inputTokens: null, outputTokens: null },
      latencyMs: performance.now() - start,
      ingestion: "mock",
      raw: { instructionFound, follow, disclose },
    };
  }

  async function askText({ prompt, text }: AskTextInput): Promise<ProviderAnswer> {
    const start = performance.now();
    // Deterministic, seeded pass-through: packages/benchmark only needs a
    // stable ProviderAdapter.askText implementation for `mock`; the actual
    // paraphrase/translation transform logic is owned by
    // packages/robustness (round 2 r4).
    const rng = createSeededRng(sha256Hex(text), sha256Hex(prompt));
    void rng(); // reserved: keeps the seed derivation exercised/deterministic for future variation.
    return {
      text,
      stopReason: "end_turn",
      refusal: false,
      usage: { inputTokens: null, outputTokens: null },
      latencyMs: performance.now() - start,
      ingestion: "mock",
      raw: { echoed: true },
    };
  }

  return {
    name: "mock",
    model,
    isConfigured: () => true,
    askWithPdf,
    askText,
  };
}
